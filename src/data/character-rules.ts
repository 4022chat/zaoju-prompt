/**
 * 拼接模板。占位符语法：
 * - {占位符}：纯占位符，维度关闭时跳过
 * - {前缀>占位符}：前缀与占位符绑定，维度关闭时前缀一并丢弃（如"手持>道具"关闭道具后"手持"也消失）
 * 维度按 characterDimensions 的顺序填充，缺失维度自动跳过占位符及其绑定前缀。
 */
export const characterPromptTemplate =
  '一位来自{时代}的{性别}{种族}{年龄}{身份}，{背景}，{体态}，{发色}{发型}，{面部}，{瞳色}，{身着>服饰}（{配色}），佩戴{配饰}，{气质}，神情{表情}，{能力}，{手持>道具}，{姿态}，{场景}，{光线}，{镜头}。';

/** 维度 id → 维度对象，便于按 id 查找 */
export const dimensionById: Record<string, CharacterDimension> = Object.fromEntries(
  characterDimensions.map((dimension) => [dimension.id, dimension]),
);

